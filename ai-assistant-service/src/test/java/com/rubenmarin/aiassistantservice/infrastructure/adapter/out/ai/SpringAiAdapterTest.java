package com.rubenmarin.aiassistantservice.infrastructure.adapter.out.ai;

import com.rubenmarin.aiassistantservice.infrastructure.adapter.out.ai.tool.EventTools;
import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.Mock;
import org.mockito.Mockito;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.ai.chat.client.ChatClient;
import org.springframework.ai.chat.messages.AssistantMessage;
import org.springframework.ai.chat.model.ChatModel;
import org.springframework.ai.chat.model.ChatResponse;
import org.springframework.ai.chat.model.Generation;
import org.springframework.ai.chat.prompt.Prompt;
import org.springframework.ai.model.tool.ToolCallingChatOptions;

import java.util.List;

@ExtendWith(MockitoExtension.class)
class SpringAiAdapterTest {

    @Mock
    private ChatModel chatModel;

    @Test
    void shouldGenerateResponse() {

        EventTools eventTools = Mockito.spy(new EventTools());

        Mockito.when(chatModel.getOptions())
                .thenReturn(ToolCallingChatOptions.builder().build());

        ChatClient chatClient = ChatClient.builder(chatModel)
                .defaultTools(eventTools)
                .build();

        // GIVEN
        String prompt = "How many seats are available for event 123?";


        // ToolCall describes which method the model wants to invoke and its JSON arguments.
        AssistantMessage.ToolCall toolCall =
                new AssistantMessage.ToolCall(
                        "call-123",
                        "function",
                        "getAvailableSeats",
                        "{\"eventId\":\"123\"}"
                );

        // AssistantMessage represents a message generated by the model.
        AssistantMessage assistantMessage =
                AssistantMessage
                        .builder()
                        .toolCalls(List.of(toolCall))
                        .build();

        //Generation wraps that assistant message.
        //ChatResponse represents the complete model response.
        ChatResponse toolCallResponse = new ChatResponse(List.of(new Generation(assistantMessage)));

        AssistantMessage finalMessage = new AssistantMessage("Event 123 has 25 available seats.");
        ChatResponse finalResponse = new ChatResponse(List.of(new Generation(finalMessage)));


        Mockito.when(chatModel.call(Mockito.any(Prompt.class)))
                .thenReturn(toolCallResponse)
                .thenReturn(finalResponse);

        String response = chatClient.prompt()
                .user(prompt)
                .call()
                .content();

        Assertions.assertEquals("Event 123 has 25 available seats.", response);

        Mockito.verify(chatModel, Mockito.times(2))
                .call(Mockito.any(Prompt.class));

        Mockito.verify(eventTools, Mockito.times(1))
                .getAvailableSeats("123");
    }

}
